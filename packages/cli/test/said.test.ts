let dir: string;
let realHome: string | undefined;

const run = (cwd: string, ...args: string[]): void => {
  execFileSync("git", ["-C", cwd, ...args], { stdio: "ignore" });
};
function seedRepo(root: string): void {
  mkdirSync(root, { recursive: true });
  run(root, "init", "-q", "-b", "main");
  run(root, "config", "user.email", "t@example.com");
  run(root, "config", "user.name", "t");
  writeFileSync(join(root, "a.ts"), "export const a = 1;\n", "utf8");
  run(root, "add", "-A");
  run(root, "commit", "-q", "-m", "first");
}

beforeEach(() => {
  dir = mkdtempSync(join(tmpdir(), "grove-said-"));
  process.env.GROVE_KNOWLEDGE_DB = join(dir, "knowledge.db");
  realHome = process.env.HOME;
  process.env.HOME = join(dir, "home");
  mkdirSync(join(dir, "home", ".claude", "projects"), { recursive: true });
});
afterEach(() => {
  delete process.env.GROVE_KNOWLEDGE_DB;
  if (realHome === undefined) delete process.env.HOME;
  else process.env.HOME = realHome;
  rmSync(dir, { recursive: true, force: true });
});

const withDB = <T>(fn: (db: NonNullable<ReturnType<typeof open>>) => T): T => {
  const db = open();
  if (!db) throw new Error("no db");
  try {
    return fn(db);
  } finally {
    db.close();
  }
};

describe("what was typed", () => {
  it("is tagged by shape, never by meaning", () => {
    expect(tagOf("remember that we deploy on tuesdays")).toBe("pin");
    expect(tagOf("no, not that one, revert it")).toBe("correction");
    expect(tagOf("cool, it was actually 8pm")).toBe("correction");
    expect(tagOf("use pnpm rather than npm here")).toBe("correction");
    expect(tagOf("let's go with postgres 16")).toBe("decision");
    expect(tagOf("why does the pool leak?")).toBe("question");
    expect(tagOf("fix the bug in capture.ts")).toBe("request");
    expect(tagOf("okay lets push this out")).toBe("request");
    expect(tagOf("also fix the flaky test please")).toBe("request");
    expect(tagOf("rebuild and install the cli")).toBe("request");
    expect(tagOf("rerun the suite and restart the daemon")).toBe("request");
    expect(tagOf("i spoke to jake at 5pm")).toBe("statement");
    expect(tagOf("the staging cluster is frozen until monday")).toBe("statement");
  });

  it("reads a keyword inside a flag or a path as the flag, not the word", () => {
    expect(tagOf("add --remember to know")).not.toBe("pin");
    expect(tagOf("remember that the release train leaves on thursdays")).toBe("pin");
    expect(tagOf("the --instead flag goes on the command")).not.toBe("correction");
    expect(tagOf("see docs/actually.md for the rest")).not.toBe("correction");
    expect(tagOf("the (remember) call is in said.ts")).not.toBe("pin");
    expect(tagOf('"remember" is the pin word')).not.toBe("pin");
    expect(tagOf("the `actually` branch is dead code")).not.toBe("correction");
  });

  it("rejects the whole turn when a machine marker is anywhere in it", () => {
    const typed = "the pool size is eight now";
    for (const marker of [
      "[Pasted text #2 +7 lines]",
      "[Image #1]",
      "3 background agents were stopped",
      "1 background agent was stopped",
      "Caveat: The messages below were generated by the user while running local commands.",
      "fact · stated by the user · ttys004",
      "updated 5:37:48 AM",
      "<task-notification>done</task-notification>",
      '<teammate-message teammate_id="x">hi</teammate-message>',
      "<bash-stdout>ok</bash-stdout>",
      "Another Claude session sent a message",
      "[Cross-session message]",
    ]) {
      expect(sentencesOf(`${typed}\n${marker}`), marker).toEqual([]);
    }
    expect(sentencesOf(`${typed}\nupdated 5:37:48 AM for real`)).toHaveLength(2);
  });

  it("drops chrome lines and keeps a typed line with a separator in it", () => {
    expect(
      sentencesOf(
        "the real line is here\n⏺ Read the file\n  ⎿ done\n    · Mike is the reviewer\n· said hello there\n  12 │ const x\n✻ Thinking",
      ),
    ).toEqual(["the real line is here"]);
    expect(sentencesOf("jake · 5pm · the renewal is on")).toEqual([
      "jake · 5pm · the renewal is on",
    ]);
    for (const typed of [
      "Read-only replicas live in us-east",
      "Bash aliases live in ~/.zshrc",
      "Running it twice fails",
      "Search for callers of fuse first",
      "3 - the third thing is broken",
    ]) {
      expect(sentencesOf(typed), typed).toEqual([typed]);
    }
  });

  it("keeps sentences a person typed and drops what was pasted or is chrome", () => {
    expect(sentencesOf("i spoke to jake at 5pm. he said the deal is on")).toEqual([
      "i spoke to jake at 5pm.",
      "he said the deal is on",
    ]);
    expect(sentencesOf("ok")).toEqual([]);
    expect(sentencesOf("<command-name>/clear</command-name>")).toEqual([]);
    expect(sentencesOf("Another Claude session sent a message: hello there friend")).toEqual([]);
    expect(sentencesOf(`${"a very long paste ".repeat(40)}`)).toEqual([]);
    expect(sentencesOf("❯ grove know\n  ⏵ ran\nthe real line is here")).toEqual([
      "the real line is here",
    ]);
  });

  it("heats on repeats and on being used, never on merely being shown", () => {
    withDB((db) => {
      const ctx = { repo: "r", source: "t1", session: "s1", branch: "main" };
      const [s] = record(db, ctx, "the pool size is 8");
      if (!s) throw new Error("nothing recorded");
      expect(heatOf(s)).toBeCloseTo(Math.log(2), 5);
      const [fix] = record(db, ctx, "cool, it was actually 16");
      expect(hot(db, "r", 10).map((h) => h.id)).toEqual([fix?.id]);
      promote(db, "r", [fix?.id ?? ""], "");
      const [again] = record(db, { ...ctx, session: "s2" }, "the pool size is 8");
      expect(again?.repeats).toBe(2);
      touched(db, "r", [s.id, s.id, s.id, s.id]);
      expect(hot(db, "r", 10)).toEqual([]);
      expect(recentSaid(db, "r", 5).find((r) => r.id === s.id)?.retrieved).toBe(4);
      // One session, however many reads, is one use; a second session is another.
      expect(markUsed(db, "r", [s.id, s.id], "s9")).toBe(1);
      expect(markUsed(db, "r", [s.id], "s9")).toBe(0);
      const now = hot(db, "r", 10);
      expect(now.map((h) => [h.text, h.used])).toEqual([["the pool size is 8", 1]]);
      expect(heatOf(now[0] as Said)).toBeCloseTo(Math.log(6), 5);
      // The retired correction goes; the hot sentence stays until it is worded or cools.
      expect(trim(db, "r", 0)).toBe(1);
      promote(db, "r", [s.id], "");
      expect(hot(db, "r", 10)).toEqual([]);
      expect(recentSaid(db, "r", 5)[0]?.promoted).toBe("");
      expect(trim(db, "r", 0)).toBe(1);
      expect(db.prepare("SELECT COUNT(*) AS n FROM said_use").get()?.n).toBe(0);
    });
  });

  it("cools with age and with every digest that declines it", () => {
    const hour = 3_600_000;
    const base: Said = {
      id: "x",
      text: "remember the train leaves on thursdays",
      tag: "pin",
      source: "t1",
      session: "s1",
      branch: null,
      at: 0,
      lastAt: 0,
      repeats: 1,
      retrieved: 40,
      used: 0,
      tries: 0,
      contested: false,
      promoted: null,
    };
    expect(heatOf(base, hour)).toBeCloseTo(2.5 + Math.log(2), 5);
    expect(heatOf(base, 60 * 24 * hour)).toBeLessThan(0);
    // Age counts from the last time it was said: a habit typed eight times over twenty
    // days is hot within the hour of the eighth, and cold three days after it.
    const habit = { ...base, tag: "statement" as const, repeats: 8, lastAt: 20 * 24 * hour };
    expect(heatOf(habit, habit.lastAt + hour)).toBeGreaterThan(HOT);
    expect(heatOf(habit, habit.lastAt + 3 * 24 * hour)).toBeLessThan(HOT);
    expect(heatOf({ ...base, tag: "statement", repeats: 3 }, 24 * hour)).toBeLessThan(HOT);
    expect(heatOf({ ...base, tag: "statement", repeats: 3 }, hour)).toBeGreaterThan(HOT);
    expect(heatOf({ ...base, tag: "statement", repeats: 3, tries: 2 }, hour)).toBeLessThan(HOT);
    expect(heatOf({ ...base, tag: "request", repeats: 50 }, hour)).toBeLessThan(0);
    expect(heatOf({ ...base, tag: "statement", contested: true }, hour)).toBeCloseTo(
      2 + Math.log(2),
      5,
    );
  });

  it("never hands a request or a question to the digest", () => {
    withDB((db) => {
      const ctx = { repo: "r", source: "t1", session: "s1", branch: "main" };
      for (const session of ["s1", "s2", "s3", "s4"]) {
        record(db, { ...ctx, session }, "rebuild and install the cli");
        record(db, { ...ctx, session }, "why does the pool leak?");
        record(db, { ...ctx, session }, "the pool leaks under load");
      }
      expect(hot(db, "r", 10).map((h) => h.text)).toEqual(["the pool leaks under load"]);
      missed(
        db,
        "r",
        hot(db, "r", 10).map((h) => h.id),
      );
      expect(recentSaid(db, "r", 5).find((s) => s.text.startsWith("the pool"))?.tries).toBe(1);
      missed(
        db,
        "r",
        hot(db, "r", 10).map((h) => h.id),
      );
      expect(hot(db, "r", 10)).toEqual([]);
    });
  });

  it("is heard by other terminals unless it was a request or a question", () => {
    withDB((db) => {
      const ctx = { repo: "r", source: "t1", session: "s1", branch: "main" };
      record(db, ctx, "i spoke to jake at 5pm");
      record(db, ctx, "fix the bug in capture.ts");
      record(db, ctx, "what time is it?");
      expect(heard(db, "r", 60_000, "t2", 5).map((s) => s.text)).toEqual([
        "i spoke to jake at 5pm",
      ]);
      expect(heard(db, "r", 60_000, "t1", 5)).toEqual([]);
    });
  });
});

describe("a sentence typed in one terminal reaches the next", () => {
  it("is found by its words, and shown as what was said", () => {
    const root = join(dir, "repo");
    seedRepo(root);
    const repo = repoID(root);
    if (!repo) throw new Error("not a repo");
    withDB((db) => {
      record(
        db,
        { repo, source: "t1", session: "s1", branch: "main" },
        "i spoke to jake at 5pm about the renewal",
      );
    });
    ingest(root, true);

    const k = retrieve(root, "when did i speak with jake", "t2");
    expect(k.notes.map((n) => [n.kind, n.title])).toEqual([
      ["said", "i spoke to jake at 5pm about the renewal"],
    ]);
    expect(k.heard.map((s) => s.text)).toEqual([]);
    expect(renderKnowledge(k, [], "t2")).toContain("said (t1, ");

    const fresh = retrieve(root, "unrelated question about nothing", "t2");
    expect(fresh.heard.map((s) => s.text)).toEqual(["i spoke to jake at 5pm about the renewal"]);
    expect(renderKnowledge(fresh, [], "t2")).toContain("· said i spoke to jake at 5pm");
    // Being shown is counted, and counts for nothing: a row heats only on use.
    withDB((db) => expect(hot(db, repo, 5)).toEqual([]));
    retrieve(root, "unrelated question about nothing", "t2");
    retrieve(root, "unrelated question about nothing", "t2");
    withDB((db) => {
      expect(hot(db, repo, 5)).toEqual([]);
      expect(recentSaid(db, repo, 5).map((s) => s.retrieved)).toEqual([4]);
    });
  });
});

describe("a plain restatement contests what is already believed", () => {
  it("takes correction heat without any correcting vocabulary, and keeps its shape", () => {
    withDB((db) => {
      const ctx = { repo: "r", source: "t1", session: "s1", branch: "main" };
      remember(db, { repo: "r", source: "t1", head: null, branch: "main" }, [
        { text: "The user spoke to Jake at 8pm.", kind: "state", stated: true },
      ]);
      record(db, ctx, "when did i speak to jake?");
      const [claim] = record(db, ctx, "i said it before, it's 10am");
      if (!claim) throw new Error("nothing recorded");
      expect(claim.tag).toBe("statement");
      expect(claim.contested).toBe(true);
      expect(heatOf(claim)).toBeGreaterThanOrEqual(HOT);
      expect(hot(db, "r", 10).map((h) => h.text)).toContain("i said it before, it's 10am");
    });
  });

  it("leaves a claim about nothing known, and small talk near a fact, cold", () => {
    withDB((db) => {
      const ctx = { repo: "r", source: "t1", session: "s1", branch: "main" };
      remember(db, { repo: "r", source: "t1", head: null, branch: "main" }, [
        { text: "The user spoke to Jake at 8pm.", kind: "state", stated: true },
      ]);
      const [far] = record(db, ctx, "the parser handles 12 cases now");
      expect(far?.tag).toBe("statement");
      record(db, ctx, "when did i speak to jake?");
      const [chat] = record(db, ctx, "that makes sense to me");
      expect(chat?.tag).toBe("statement");
      expect(hot(db, "r", 10)).toEqual([]);
    });
  });
});
