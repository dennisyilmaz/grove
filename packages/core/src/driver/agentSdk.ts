/**
 * Credential resolution puts ANTHROPIC_API_KEY / ANTHROPIC_AUTH_TOKEN ahead of the
 * subscription login (even empty strings claim their slot), so a stray exported key
 * would silently shift sessions from the user's plan onto pay-per-token API billing.
 * Every session env is scrubbed; the M0 spike asserts apiKeySource stays "oauth".
 */
export function scrubbedEnv(): Record<string, string | undefined> {
  const env: Record<string, string | undefined> = { ...process.env };
  delete env.ANTHROPIC_API_KEY;
  delete env.ANTHROPIC_AUTH_TOKEN;
  delete env.ANTHROPIC_PROFILE;
  delete env.GEMINI_API_KEY;
  delete env.GOOGLE_API_KEY;
  env.CLAUDE_AGENT_SDK_CLIENT_APP = "grove/0.1.0";
  return env;
}

/** Name the session types to publish its branch. Also the command in prompts. */
export const PUSH_COMMAND = "grove-push";

/**
 * Write a single-purpose `grove-push` executable into a throwaway directory and
 * return it, for the caller to put on the session's PATH.
 *
 * The branch and repo are baked into the file at generation time, and the script
 * ignores every argument it is given, so there is no input through which a
 * session could redirect the push. That is the whole design: `git push` stays
 * denied for every role because no deny-list regex can reliably say "this branch
 * and no other" across `git push origin HEAD:main`, a configured upstream,
 * `--mirror`, `--all`, and `git -C ..`. Here the refspec is not something the
 * session gets to write.
 *
 * Values are single-quoted with `'` doubled, so a branch name containing a quote
 * cannot close the string and append a command.
 */
export function writePushShim(push: { repo: string; branch: string }): { dir: string } {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "grove-push-"));
  const sq = (s: string) => `'${s.replaceAll("'", "'\\''")}'`;
  const refspec = `refs/heads/${push.branch}:refs/heads/${push.branch}`;
  fs.writeFileSync(
    path.join(dir, PUSH_COMMAND),
    [
      "#!/bin/sh",
      "# Generated by grove for one session. Arguments are ignored on purpose.",
      "set -e",
      `exec git -C ${sq(push.repo)} push origin ${sq(refspec)}`,
      "",
    ].join("\n"),
    { mode: 0o755 },
  );
  return { dir };
}

interface Denial {
  tool: string;
  reason: string;
}

function buildPreToolUseHook(spec: SessionSpec, denials: Denial[]): HookCallback {
  const rolePolicy = ROLE_TOOL_POLICY[spec.role];
  return async (input) => {
    if (input.hook_event_name !== "PreToolUse") return {};
    const toolName = input.tool_name;

    const denyWith = (reason: string) => {
      denials.push({ tool: toolName, reason });
      return {
        hookSpecificOutput: {
          hookEventName: "PreToolUse" as const,
          permissionDecision: "deny" as const,
          permissionDecisionReason: reason,
        },
      };
    };

    // Backstop for the tool floor — fires even if base-set restriction were a no-op.
    if (rolePolicy.disallowed.includes(toolName)) {
      return denyWith(`tool ${toolName} is not available to the ${spec.role} role`);
    }

    if (spec.scope) {
      const writePath = extractWritePath(toolName, input.tool_input);
      if (writePath !== null) {
        const decision = checkWritePath(writePath, spec.scope);
        if (!decision.allow) return denyWith(decision.reason);
      }
    }

    if (toolName === "Bash") {
      const command =
        typeof input.tool_input === "object" && input.tool_input !== null
          ? String((input.tool_input as Record<string, unknown>).command ?? "")
          : "";
      const decision = checkBash(command);
      if (!decision.allow) return denyWith(decision.reason);
    }

    return {};
  };
}

/** What the graph knows for the prompt rides in as context, exactly as a terminal's hook injects it. */
export function buildUserPromptSubmitHook(
  spec: SessionSpec,
  knowledge: Pick<Knowledge, "inject">,
): HookCallback {
  return async (input) => {
    if (input.hook_event_name !== "UserPromptSubmit") return {};
    let context = "";
    try {
      context = await knowledge.inject(
        {
          cwd: input.cwd,
          session_id: input.session_id,
          transcript_path: input.transcript_path,
          prompt: input.prompt,
        },
        spec.source,
      );
    } catch {
      // A prompt must always go through; the graph is context, never a gate.
    }
    if (!context) return {};
    return {
      hookSpecificOutput: {
        hookEventName: "UserPromptSubmit" as const,
        additionalContext: context,
      },
    };
  };
}

export class AgentSdkDriver implements Driver {
  /**
   * `sandbox: null` runs tools unconfined — only for a host that cannot provide
   * an OS sandbox, chosen explicitly with `GROVE_SANDBOX=0`.
   */
  constructor(
    private readonly opts: { sandbox: SandboxTargets | null; knowledge?: Knowledge } = {
      sandbox: null,
    },
  ) {}

  run(spec: SessionSpec): SessionHandle {
    const rolePolicy = ROLE_TOOL_POLICY[spec.role];
    const denials: Denial[] = [];
    const preToolUse: HookCallbackMatcher = { hooks: [buildPreToolUseHook(spec, denials)] };
    // Reviewers are excluded — fresh eyes stay fresh.
    const knowledge = spec.role !== "reviewer" ? this.opts.knowledge : undefined;
    const userPromptSubmit: HookCallbackMatcher[] = knowledge
      ? [{ hooks: [buildUserPromptSubmitHook(spec, knowledge)] }]
      : [];

    const shim = spec.push ? writePushShim(spec.push) : null;
    const env = scrubbedEnv();
    if (shim) env.PATH = `${shim.dir}${path.delimiter}${env.PATH ?? ""}`;
    if (spec.source) env.GROVE_SOURCE = spec.source;
    const sdkModel = normalizeModelForSdk(spec.model);

    const options: Options = {
      cwd: spec.cwd,
      permissionMode: "dontAsk",
      tools: rolePolicy.tools,
      allowedTools: rolePolicy.tools,
      disallowedTools: rolePolicy.disallowed,
      settingSources: [],
      // Flag-tier settings: replace Claude Code's default commit/PR attribution
      // with grove's. Never "Co-Authored-By: Claude ...".
      extraArgs: {
        settings: JSON.stringify({
          attribution: {
            commit: groveTrailer(spec.model ?? null),
            pr: "Built by grove",
          },
        }),
      },
      env,
      hooks: {
        PreToolUse: [preToolUse],
        ...(knowledge && { UserPromptSubmit: userPromptSubmit }),
      },
      ...(this.opts.sandbox !== null && { sandbox: sandboxSettings(this.opts.sandbox) }),
      ...(sdkModel !== undefined && { model: sdkModel }),
      ...(spec.maxTurns !== undefined && { maxTurns: spec.maxTurns }),
      ...(spec.resumeSessionId !== undefined && { resume: spec.resumeSessionId }),
    };

    // Streaming input: the initial prompt seeds the session; the queue stays
    // open so the daemon can steer the live session with human guidance
    // (priority "now" merges into the turn in flight). The queue closes when a
    // result lands with nothing buffered, restoring one-shot lifecycle.
    const steering = new InputQueue();
    async function* input(): AsyncGenerator<SDKUserMessage> {
      yield {
        type: "user",
        message: { role: "user", content: spec.prompt },
        parent_tool_use_id: null,
      };
      for await (const text of steering.drain()) {
        yield {
          type: "user",
          message: { role: "user", content: text },
          parent_tool_use_id: null,
          priority: "now",
        };
      }
    }

    const q = query({ prompt: input(), options });

    async function* events(): AsyncGenerator<SessionEvent> {
      const flushDenials = function* (): Generator<SessionEvent> {
        while (denials.length > 0) {
          const d = denials.shift()!;
          yield { type: "tool_denied", tool: d.tool, reason: d.reason };
        }
      };
      try {
        for await (const msg of q as AsyncIterable<SDKMessage>) {
          yield* flushDenials();
          if (msg.type === "system" && msg.subtype === "init") {
            yield {
              type: "init",
              sessionId: msg.session_id,
              model: msg.model,
              tools: msg.tools,
              apiKeySource: msg.apiKeySource,
            };
          } else if (msg.type === "system" && msg.subtype === "api_retry") {
            // Visibility only — the SDK owns this backoff and is already
            // handling it. What the daemon adds is a record that the quiet was
            // the API's, not the model's.
            yield {
              type: "api_retry",
              attempt: msg.attempt,
              maxRetries: msg.max_retries,
              delayMs: msg.retry_delay_ms,
              status: msg.error_status,
              // A classification, not prose: 'rate_limit', 'overloaded', …
              message: msg.error,
            };
          } else if (msg.type === "assistant") {
            for (const block of msg.message.content) {
              if (block.type === "text" && block.text.length > 0) {
                yield { type: "text", text: block.text };
              } else if (block.type === "tool_use") {
                yield { type: "tool_use", tool: block.name, input: block.input };
              }
            }
          } else if (msg.type === "result") {
            yield* flushDenials();
            // No steering pending → end the input stream so the session closes.
            // A message pushed mid-run already left the buffer; one pushed after
            // this point is refused and falls back to next-session delivery.
            if (steering.isEmpty) steering.close();
            const ok = msg.subtype === "success" && !msg.is_error;
            yield {
              type: "done",
              ok,
              sessionId: msg.session_id,
              result: msg.subtype === "success" ? msg.result : "",
              ...(msg.subtype !== "success" && {
                errorMessage: `session ended: ${msg.subtype}${
                  "errors" in msg && msg.errors.length > 0 ? ` — ${msg.errors.join("; ")}` : ""
                }`,
              }),
              costUsd: msg.total_cost_usd,
              numTurns: msg.num_turns,
            };
          }
        }
      } catch (err) {
        // The SDK throws for what never became a session: the CLI failing to
        // start, the transport dying mid-stream, auth being refused. Left to
        // propagate it reached the flow as a bare exception, so the round ended
        // with no `session.done` and the reason lived only in the daemon log.
        // As a `done` event it is an outcome like any other — visible in the
        // feed, and classifiable as transient by the caller.
        yield {
          type: "done",
          ok: false,
          sessionId: null,
          result: "",
          errorMessage: `session stream failed: ${err instanceof Error ? err.message : String(err)}`,
        };
      } finally {
        // The stream ending for ANY reason (error, no result) must release the
        // input generator, or the queue would keep the session graph alive.
        steering.close();
        // The shim outlives nothing: once the session is over there is no
        // process left that should be able to publish this branch.
        if (shim) fs.rmSync(shim.dir, { recursive: true, force: true });
      }
      yield* flushDenials();
    }

    return {
      events: events(),
      interrupt: () => {
        steering.close();
        return q.interrupt();
      },
      postMessage: (text) => steering.push(text),
    };
  }
}
